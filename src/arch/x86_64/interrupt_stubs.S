// Common interrupt handler that saves all registers
.global interrupt_common_stub
interrupt_common_stub:
    // Save all general purpose registers
    push %rax
    push %rbx
    push %rcx
    push %rdx
    push %rsi
    push %rdi
    push %rbp
    push %r8
    push %r9
    push %r10
    push %r11
    push %r12
    push %r13
    push %r14
    push %r15

    // Save segment registers (though they're mostly unused in 64-bit)
    mov %ds, %rax
    push %rax
    mov %es, %rax
    push %rax
    mov %fs, %rax
    push %rax
    mov %gs, %rax
    push %rax

    // Load kernel data segment
    mov $0x10, %ax
    mov %ax, %ds
    mov %ax, %es

    // Call the C interrupt handler with RSP as argument
    mov %rsp, %rdi
    call interrupt_dispatcher

    // Restore segment registers
    pop %rax
    mov %rax, %gs
    pop %rax
    mov %rax, %fs
    pop %rax
    mov %rax, %es
    pop %rax
    mov %rax, %ds

    // Restore general purpose registers
    pop %r15
    pop %r14
    pop %r13
    pop %r12
    pop %r11
    pop %r10
    pop %r9
    pop %r8
    pop %rbp
    pop %rdi
    pop %rsi
    pop %rdx
    pop %rcx
    pop %rbx
    pop %rax

    // Remove error code and vector number from stack
    add $16, %rsp

    // Return from interrupt
    iretq

// Generate interrupt stubs
.macro ISR_NOERRCODE num
.global isr\num
isr\num:
    cli
    pushq $0        // Push dummy error code
    pushq $\num     // Push vector number
    jmp interrupt_common_stub
.endm

.macro ISR_ERRCODE num
.global isr\num
isr\num:
    cli
    pushq $\num     // Push vector number (error code already pushed by CPU)
    jmp interrupt_common_stub
.endm

